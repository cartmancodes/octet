#!/usr/bin/env node
// Generates src/mascot/poses.ts from the terminal UI's pixel-art SVGs
// (docs/design/octet-agent-modes). The SVGs carry large C2PA manifests; only
// the viewBox and the shapes are read, so none of that reaches the app.
// Each colour is merged into one path. No dependencies: the SVGs are plain,
// machine-written XML, so a small attribute parser is enough.
//
//   node scripts/mascot.mjs            write src/mascot/poses.ts
//   node scripts/mascot.mjs --stdout   print it instead (the test compares)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const svgDir = path.resolve(here, "..", "..", "..", "docs", "design", "octet-agent-modes");
const outFile = path.resolve(here, "..", "src", "mascot", "poses.ts");

export const POSES = [
  "idle",
  "thinking",
  "coding",
  "searching",
  "delegating",
  "approval",
  "success",
  "error",
  "sleeping",
];

function attrs(tag) {
  const found = {};
  for (const match of tag.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) found[match[1]] = match[2];
  return found;
}

/** One pose: its viewBox and one path-data string per fill, in first-seen order. */
export function parse(name, svg) {
  // Drop the metadata block (the C2PA manifest) before anything else is read.
  const body = svg.replace(/<metadata[\s\S]*?<\/metadata>/g, "");
  const root = /<svg\b[^>]*>/.exec(body);
  const viewBox = root ? attrs(root[0]).viewBox : undefined;
  if (!viewBox || !/^\d+ \d+ \d+ \d+$/.test(viewBox)) {
    throw new Error(`${name}: missing or odd viewBox`);
  }
  const byFill = new Map();
  const add = (fill, d) => {
    if (!/^#[0-9a-fA-F]{6}$/.test(fill ?? "")) throw new Error(`${name}: bad fill ${fill}`);
    const key = fill.toLowerCase();
    byFill.set(key, (byFill.get(key) ?? "") + d);
  };
  for (const [tag] of body.matchAll(/<(rect|path)\b[^>]*>/g)) {
    const a = attrs(tag);
    if (tag.startsWith("<path")) {
      if (!a.d || /[^MmHhVvZz0-9.\s-]/.test(a.d)) throw new Error(`${name}: unsupported path`);
      add(a.fill, a.d);
    } else {
      const [x, y, w, h] = ["x", "y", "width", "height"].map((k) => Number(a[k] ?? 0));
      if (![x, y, w, h].every(Number.isFinite)) throw new Error(`${name}: bad rect`);
      add(a.fill, `M${x} ${y}h${w}v${h}h${-w}Z`);
    }
  }
  if (byFill.size === 0) throw new Error(`${name}: no shapes`);
  return { viewBox, paths: [...byFill].map(([fill, d]) => ({ fill, d })) };
}

export function generate() {
  const poses = POSES.map((name) => {
    const svg = readFileSync(path.join(svgDir, `octet-${name}.svg`), "utf8");
    return [name, parse(name, svg)];
  });
  const lines = [
    "// Generated by scripts/mascot.mjs from docs/design/octet-agent-modes/*.svg. Do not edit.",
    "// Run `npm run mascot` to regenerate; a test fails if this file is stale.",
    "",
    `export const POSE_NAMES = ${JSON.stringify(POSES)} as const;`,
    "",
    "export type PoseName = (typeof POSE_NAMES)[number];",
    "",
    "/** One colour of a pose: all its pixels as a single path. */",
    "export interface PosePath {",
    "  fill: string;",
    "  d: string;",
    "}",
    "",
    "export interface Pose {",
    "  viewBox: string;",
    "  paths: readonly PosePath[];",
    "}",
    "",
    "export const POSES: Record<PoseName, Pose> = {",
  ];
  for (const [name, pose] of poses) {
    lines.push(`  ${name}: {`, `    viewBox: ${JSON.stringify(pose.viewBox)},`, "    paths: [");
    for (const p of pose.paths) {
      lines.push(`      { fill: ${JSON.stringify(p.fill)}, d: ${JSON.stringify(p.d)} },`);
    }
    lines.push("    ],", "  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--stdout")) process.stdout.write(text);
  else {
    writeFileSync(outFile, text);
    process.stderr.write(`wrote ${outFile} (${text.length} bytes)\n`);
  }
}
